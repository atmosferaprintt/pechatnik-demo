-- 025: защита от задвоенных записей в деньгах (случай Марьян 2026-09-17).
--
-- Что было: сотрудница записывала доставку 650 ₽, связь тормозила, кнопка «Записать» никак
-- не блокировалась — она нажала несколько раз. Запросы висели в очереди и, когда связь ожила,
-- ушли на сервер пачкой: 8 одинаковых расходов за 85 миллисекунд (15:08:11.837…15:08:11.922),
-- в ленте «Доставка + Доставка + …» на −5 200 ₽. Удалить их сотрудница не могла: кнопки нет.
--
-- Интерфейс теперь гасит кнопку на время отправки, но этого мало: перезагрузила страницу,
-- нажала снова — и дубль опять возможен. Поэтому страховка в базе: форма присваивает каждой
-- строке операции ключ (client_op_id) и переиспользует его при повторной отправке, пока запись
-- не прошла. Уникальный индекс не даст записать ту же строку дважды — повтор вернёт 23505,
-- и клиент считает это «уже записано».
--
-- Индекс частичный: у старых записей ключа нет, и NULL-ы уникальности не мешают.

alter table transactions add column if not exists client_op_id uuid;

create unique index if not exists transactions_client_op_id_uniq
  on transactions (client_op_id) where client_op_id is not null;

grant insert (client_op_id) on transactions to authenticated;
