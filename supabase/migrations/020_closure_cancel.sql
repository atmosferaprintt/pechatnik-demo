-- можно ли как-то это менять?» — после закрытия форма исчезает, отменить нельзя).
-- Кнопка «отменить» удаляет строку day_closures — форма закрытия появляется снова,
-- переходящий остаток пересчитывается сам. Владелец может всё (dc_owner);
-- сотрудницам разрешаем DELETE в том же окне сегодня/вчера, что и закрытие/пересчёт (002, 017).
create policy dc_employee_delete on day_closures for delete to authenticated
  using (not is_owner() and close_date between current_date - 1 and current_date);
